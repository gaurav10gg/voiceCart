function variants(
  prefix: string,
  sizes: string[],
  colors: { color: string; hex: string; price?: number; stock?: number }[],
  price: number,
  stock = 4,
): Variant[] {
  const out: Variant[] = [];
  for (const size of sizes) {
    for (const c of colors) {
      const code = `${prefix}-${size}-${c.color.slice(0, 3).toUpperCase()}`;
      out.push({
        sku: code,
        size,
        color: c.color,
        hex: c.hex,
        price: c.price ?? price,
        stock: c.stock ?? stock,
      });
    }
  }
  return out;
}

