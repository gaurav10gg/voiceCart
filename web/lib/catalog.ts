export function getProduct(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function getVariant(sku: string): { product: Product; variant: Variant } | undefined {
  for (const product of PRODUCTS) {
    const variant = product.variants.find((v) => v.sku === sku);
    if (variant) return { product, variant };
  }
  return undefined;
}

export function inStockVariants(product: Product) {
  return product.variants.filter((v) => v.stock > 0);
}

export function availableSizes(product: Product, color?: string) {
  return [
    ...new Set(
      inStockVariants(product)
        .filter((v) => !color || v.color.toLowerCase() === color.toLowerCase())
        .map((v) => v.size),
    ),
  ];
}

export function availableColors(product: Product, size?: string) {
  const colors = inStockVariants(product)
    .filter((v) => !size || v.size.toLowerCase() === size.toLowerCase())
    .map((v) => ({ color: v.color, hex: v.hex }));
  const seen = new Set<string>();
  return colors.filter((c) => {
    if (seen.has(c.color)) return false;
    seen.add(c.color);
    return true;
  });
}

export function findVariant(product: Product, size?: string, color?: string) {
  const matches = inStockVariants(product).filter((v) => {
    const sizeOk = !size || v.size.toLowerCase() === size.toLowerCase();
    const colorOk = !color || v.color.toLowerCase() === color.toLowerCase();
    return sizeOk && colorOk;
  });
  return matches;
}
